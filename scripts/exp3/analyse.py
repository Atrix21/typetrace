#!/usr/bin/env python3
"""
Experiment 3 stage-1 analysis (retrieval only). Reads results/stage1-{S,M,L}/metrics.jsonl (+ infra, graph builds)
and writes results/stage1-analysis.json and results/stage1-report.md.

Unit of analysis = task. Paired differences use a task-level bootstrap (10,000 resamples, seed 20261110);
one-sided p-values for the pre-registered directional hypotheses use a paired sign-flip permutation test
(exact up to 2^n <= 65536, else 20,000 random flips). Holm correction over the confirmatory family {H1, H2}.

  python -I scripts/exp3/analyse.py [--split test]
"""
import argparse, json, math, os, random, statistics
from collections import defaultdict

EXP = 'experiments/03-graph-scale'
SEED = 20261110
B = 10000


def load(repo):
    p = f'{EXP}/results/stage1-{repo}/metrics.jsonl'
    if not os.path.exists(p):
        return []
    return [json.loads(l) for l in open(p) if l.strip()]


def mean(xs):
    xs = [x for x in xs if x is not None]
    return statistics.fmean(xs) if xs else None


def boot_ci(xs, seed=SEED):
    xs = [x for x in xs if x is not None]
    if not xs:
        return (None, None)
    r = random.Random(seed)
    n = len(xs)
    ms = sorted(statistics.fmean(r.choices(xs, k=n)) for _ in range(B))
    return (ms[int(0.025 * B)], ms[int(0.975 * B) - 1])


def perm_p(diffs, seed=SEED):
    """One-sided P(mean >= observed) under random sign flips (H0: symmetric around 0)."""
    d = [x for x in diffs if x is not None]
    n = len(d)
    if n == 0:
        return None
    obs = statistics.fmean(d)
    if n <= 16:
        cnt = tot = 0
        for m in range(1 << n):
            s = sum(x if (m >> i) & 1 else -x for i, x in enumerate(d)) / n
            cnt += s >= obs - 1e-12
            tot += 1
        return cnt / tot
    r = random.Random(seed)
    cnt = 0
    for _ in range(20000):
        s = sum(x if r.random() < 0.5 else -x for x in d) / n
        cnt += s >= obs - 1e-12
    return (cnt + 1) / 20001


def holm(ps):
    order = sorted((p, k) for k, p in ps.items() if p is not None)
    out, run = {}, 0.0
    m = len(order)
    for i, (p, k) in enumerate(order):
        run = max(run, min(1.0, (m - i) * p))
        out[k] = run
    return out


def fmt(x, d=3):
    return '—' if x is None else (f'{x:.{d}f}' if isinstance(x, float) else str(x))


def ci_s(ci, d=2):
    return '—' if ci[0] is None else f'[{ci[0]:+.{d}f}, {ci[1]:+.{d}f}]'


def table_rows(rows, key):
    """task_id -> method -> metric (rows from one corpus)."""
    t = defaultdict(dict)
    for r in rows:
        v = r
        for k in key.split('.'):
            v = v.get(k) if isinstance(v, dict) else None
        t[r['task_id']][r['method']] = v
    return t


def paired(rows, a, b, key):
    t = table_rows(rows, key)
    return {tid: m[a] - m[b] for tid, m in t.items() if m.get(a) is not None and m.get(b) is not None}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--split', default='test')
    a = ap.parse_args()
    res = {'split': a.split, 'repos': {}, 'contrasts': {}, 'nested': {}, 'confirmatory': {}}
    md = []
    allrows = {}
    for repo in ['S', 'M', 'L']:
        rows = [r for r in load(repo) if (a.split == 'all' or r.get('split') == a.split)]
        allrows[repo] = rows
    methods = ['ripgrep', 'bm25', 'embeddings', 'hybrid_nograph', 'hybrid', 'custom_graph', 'compact_nograph', 'compact_graph']
    metrics = [('sym_recall_5', 'Recall@5'), ('sym_recall_10', 'Recall@10'), ('sym_precision_5', 'P@5'), ('sym_precision_10', 'P@10'),
               ('rc_mrr', 'RC MRR (A)'), ('natural_recall', 'Recall (natural output)'), ('path_recall_10', 'Path recall@10'),
               ('impact_f1_20', 'Impact F1@20'), ('native_context_tokens', 'Native tokens')]
    budgets = ['500', '800', '1000', '2000', '4000', '8000']

    md.append(f'# Experiment 3 stage 1: retrieval-only results ({a.split} split)\n')
    md.append('Generated by `scripts/exp3/analyse.py` from `results/stage1-*/metrics.jsonl`. Unit = task; 95% CIs are task-level bootstrap (10k). No model calls.\n')
    for repo in ['S', 'M', 'L']:
        rows = [r for r in allrows[repo] if r['corpus'] == 'full']
        if not rows:
            continue
        tasks = sorted({r['task_id'] for r in rows})
        res['repos'][repo] = {'tasks': len(tasks), 'methods': {}}
        md.append(f'\n## {repo}: full corpus, {len(tasks)} tasks\n')
        md.append('| Method | ' + ' | '.join(n for _, n in metrics) + ' |')
        md.append('|---|' + '---:|' * len(metrics))
        for m in methods:
            mr = [r for r in rows if r['method'] == m]
            if not mr:
                continue
            vals = {}
            cells = []
            for k, n in metrics:
                sel = [r for r in mr if r.get(k) is not None and (k != 'rc_mrr' or r.get('task_type') == 'bug_localisation')]
                v = mean([r[k] for r in sel])
                vals[k] = {'mean': v, 'ci': boot_ci([r[k] for r in sel]), 'n': len(sel)}
                cells.append(fmt(v, 0) if k == 'native_context_tokens' else fmt(v, 2))
            vals['recall_at_budget'] = {b: mean([r['recall_at_budget_v2'][b] for r in mr]) for b in budgets}
            res['repos'][repo]['methods'][m] = vals
            md.append(f'| {m} | ' + ' | '.join(cells) + ' |')
        md.append('\nRecall of relevant symbols within fixed token budgets (uniform rendering, as in experiment 1):\n')
        md.append('| Method | ' + ' | '.join(f'{b} tok' for b in budgets) + ' |')
        md.append('|---|' + '---:|' * len(budgets))
        for m in methods:
            if m in res['repos'][repo]['methods']:
                md.append(f'| {m} | ' + ' | '.join(fmt(res['repos'][repo]['methods'][m]['recall_at_budget'][b], 2) for b in budgets) + ' |')

    # ---- primary contrasts on the full corpus
    contrasts = [('hybrid', 'hybrid_nograph', 'Δ_graph (primary)'), ('custom_graph', 'hybrid_nograph', 'custom graph − hybrid_nograph'),
                 ('compact_graph', 'compact_nograph', 'compact graph − compact no-graph'), ('hybrid_nograph', 'bm25', 'hybrid_nograph − BM25'),
                 ('hybrid_nograph', 'embeddings', 'hybrid_nograph − embeddings')]
    md.append('\n## Paired contrasts (full corpus; mean difference [95% CI], W/L/T, one-sided permutation p)\n')
    for key, label in [('sym_recall_10', 'Recall@10'), ('natural_recall', 'Recall (natural output)'), ('recall_at_budget_v2.1000', 'Recall within 1k tokens'),
                       ('recall_at_budget_v2.4000', 'Recall within 4k tokens'), ('rc_mrr', 'RC MRR (category A)'), ('path_recall_10', 'Path recall@10 (B–E)')]:
        md.append(f'\n### {label}\n')
        md.append('| Contrast | Repo | n | mean Δ | 95% CI | W/L/T | p |')
        md.append('|---|---|---:|---:|---|---|---:|')
        for A, Bm, name in contrasts:
            for repo in ['S', 'M', 'L', 'M+L']:
                rows = [r for rp in (['M', 'L'] if repo == 'M+L' else [repo]) for r in allrows[rp] if r['corpus'] == 'full']
                if key == 'rc_mrr':
                    rows = [r for r in rows if r.get('task_type') == 'bug_localisation']
                if key.startswith('path_recall'):
                    rows = [r for r in rows if r.get('path_recall_10') is not None]
                rows = [dict(r, task_id=f"{r['repo']}:{r['task_id']}") for r in rows]
                d = paired(rows, A, Bm, key)
                if not d:
                    continue
                xs = list(d.values())
                w = sum(x > 1e-9 for x in xs); l = sum(x < -1e-9 for x in xs)
                p = perm_p(xs)
                ci = boot_ci(xs)
                res['contrasts'][f'{name}|{key}|{repo}'] = {'n': len(xs), 'mean': mean(xs), 'ci': ci, 'w': w, 'l': l, 't': len(xs) - w - l, 'p_one_sided': p}
                md.append(f'| {name} | {repo} | {len(xs)} | {mean(xs):+.3f} | {ci_s(ci)} | {w}/{l}/{len(xs) - w - l} | {fmt(p, 3)} |')

    # ---- strata (M+L, full corpus): difficulty and locality
    md.append('\n## Δ_graph (hybrid − hybrid_nograph, Recall@10) by stratum (M+L, full corpus)\n')
    md.append('| Stratum | n | mean Δ | 95% CI | W/L/T |')
    md.append('|---|---:|---:|---|---|')
    rowsML = [dict(r, task_id=f"{r['repo']}:{r['task_id']}") for rp in ['M', 'L'] for r in allrows[rp] if r['corpus'] == 'full']
    strata = {}
    for dim in ['difficulty', 'locality']:
        for val in sorted({(r.get('strata') or {}).get(dim) for r in rowsML if r.get('strata')} - {None}):
            sub = [r for r in rowsML if (r.get('strata') or {}).get(dim) == val]
            d = paired(sub, 'hybrid', 'hybrid_nograph', 'sym_recall_10')
            xs = list(d.values())
            if not xs:
                continue
            ci = boot_ci(xs)
            strata[f'{dim}={val}'] = {'n': len(xs), 'mean': mean(xs), 'ci': ci, 'diffs': d}
            w = sum(x > 1e-9 for x in xs); l = sum(x < -1e-9 for x in xs)
            md.append(f'| {dim} = {val} | {len(xs)} | {mean(xs):+.3f} | {ci_s(ci)} | {w}/{l}/{len(xs) - w - l} |')
    res['strata'] = {k: {kk: vv for kk, vv in v.items() if kk != 'diffs'} for k, v in strata.items()}
    # H2: cross-module minus local (difference of stratum means; stratified bootstrap)
    cm, lo = strata.get('locality=cross_module'), strata.get('locality=local')
    h2 = None
    if cm and lo:
        xc, xl = list(cm['diffs'].values()), list(lo['diffs'].values())
        r = random.Random(SEED)
        bs = sorted(statistics.fmean(r.choices(xc, k=len(xc))) - statistics.fmean(r.choices(xl, k=len(xl))) for _ in range(B))
        obs = statistics.fmean(xc) - statistics.fmean(xl)
        pooled = xc + xl
        cnt = 0
        rr = random.Random(SEED + 1)
        for _ in range(20000):
            rr.shuffle(pooled)
            cnt += statistics.fmean(pooled[:len(xc)]) - statistics.fmean(pooled[len(xc):]) >= obs - 1e-12
        h2 = {'estimate': obs, 'ci': (bs[int(0.025 * B)], bs[int(0.975 * B) - 1]), 'p_one_sided': (cnt + 1) / 20001, 'n_cross': len(xc), 'n_local': len(xl)}
    res['confirmatory']['H2'] = h2

    # ---- H1: nested corpora (L)
    nested_rows = [r for r in allrows['L'] if r['corpus'] != 'full' or True]
    by_task = defaultdict(lambda: defaultdict(dict))  # task -> corpus -> method -> (lines, recall)
    for r in allrows['L']:
        by_task[r['task_id']][r['corpus']][r['method']] = (r.get('corpus_lines'), r['sym_recall_10'], r.get('strategy'))
    full_lines = None
    cpath = f'{EXP}/manifests/communities-twenty.json'
    if os.path.exists(cpath):
        full_lines = json.load(open(cpath))['total_lines']
    md.append('\n## H1: does the graph contribution grow with corpus size? (L, nested corpora)\n')
    md.append('Per task: OLS slope of Δ_graph (hybrid − hybrid_nograph, Recall@10) on log10(corpus lines) across that task\'s corpora (two subsets + the full corpus). Mean slope over tasks with a task-level bootstrap CI; one-sided permutation p for slope > 0.\n')
    md.append('| Strategy | tasks | mean slope per 10× | 95% CI | p (slope > 0) | mean Δ by size (small / medium / full) |')
    md.append('|---|---:|---:|---|---:|---|')
    for strat in ['community', 'random']:
        slopes, levels = [], defaultdict(list)
        for tid, cs in by_task.items():
            pts = []
            for cname, ms in cs.items():
                if not (cname == 'full' or cname.startswith(strat + '-')):
                    continue
                if 'hybrid' not in ms or 'hybrid_nograph' not in ms:
                    continue
                lines = ms['hybrid'][0] if cname != 'full' else full_lines
                if not lines:
                    continue
                d = ms['hybrid'][1] - ms['hybrid_nograph'][1]
                pts.append((math.log10(lines), d))
                levels['full' if cname == 'full' else cname.split('-')[1]].append(d)
            if len(pts) >= 3:
                xb = statistics.fmean(p[0] for p in pts); yb = statistics.fmean(p[1] for p in pts)
                sxx = sum((p[0] - xb) ** 2 for p in pts)
                slopes.append(sum((p[0] - xb) * (p[1] - yb) for p in pts) / sxx if sxx else 0.0)
        if not slopes:
            continue
        ci = boot_ci(slopes)
        p = perm_p(slopes)
        lv = ' / '.join(fmt(mean(levels[k]), 3) for k in sorted([k for k in levels if k != 'full'], key=int) + ['full'])
        res['nested'][strat] = {'tasks': len(slopes), 'mean_slope': mean(slopes), 'ci': ci, 'p_one_sided': p, 'mean_delta_by_level': {k: mean(v) for k, v in levels.items()}}
        md.append(f'| {strat} | {len(slopes)} | {mean(slopes):+.3f} | {ci_s(ci, 3)} | {fmt(p, 3)} | {lv} |')
    res['confirmatory']['H1'] = res['nested'].get('community')

    hp = holm({'H1': (res['confirmatory'].get('H1') or {}).get('p_one_sided'), 'H2': (h2 or {}).get('p_one_sided')})
    res['confirmatory']['holm'] = hp
    md.append('\n## Confirmatory family (Holm over H1, H2; H3/H4 need the agent stage and were not run)\n')
    md.append('| ID | Estimate | 95% CI | p (one-sided) | Holm | Minimum effect (protocol §4.4) |')
    md.append('|---|---:|---|---:|---:|---|')
    h1 = res['confirmatory'].get('H1')
    if h1:
        md.append(f"| H1 slope (community corpora) | {h1['mean_slope']:+.3f} per 10× | {ci_s(h1['ci'], 3)} | {fmt(h1['p_one_sided'], 3)} | {fmt(hp.get('H1'), 3)} | +0.05 per 10× (falsified if CI upper < +0.03) |")
    if h2:
        md.append(f"| H2 cross-module − local | {h2['estimate']:+.3f} | {ci_s(h2['ci'], 3)} | {fmt(h2['p_one_sided'], 3)} | {fmt(hp.get('H2'), 3)} | +0.05 (falsified if CI upper < +0.05) |")
    # ---- infrastructure (all tasks of the run, both splits)
    md.append('\n## Infrastructure and scaling costs\n')
    md.append('| Repo | Graph builds | build wall s (median / max) | peak RSS GB (max) | graph nodes / edges (median) | SQLite MB (median) |')
    md.append('|---|---:|---|---:|---|---:|')
    infra = {}
    for repo in ['M', 'L']:
        gp = f'{EXP}/results/stage1-{repo}/graph-builds.jsonl'
        if not os.path.exists(gp):
            continue
        gb = [json.loads(l) for l in open(gp) if l.strip()]
        gb = [g for g in gb if g.get('wall_ms') is not None]
        if not gb:
            continue
        w = sorted(g['wall_ms'] / 1000 for g in gb); rssm = max((g.get('peak_rss_mb') or 0) for g in gb) / 1000
        nn = sorted(g.get('nodes') or 0 for g in gb); ne = sorted(g.get('edges') or 0 for g in gb); sq = sorted((g.get('sqlite_bytes') or 0) / 1e6 for g in gb)
        infra[repo] = {'builds': len(gb), 'wall_s_median': w[len(w) // 2], 'wall_s_max': w[-1], 'peak_rss_gb': rssm}
        md.append(f'| {repo} | {len(gb)} | {w[len(w) // 2]:.0f} / {w[-1]:.0f} | {rssm:.1f} | {nn[len(nn) // 2]:,} / {ne[len(ne) // 2]:,} | {sq[len(sq) // 2]:.0f} |')
        fr = [g['freshness'] for g in gb if g.get('freshness')]
        if fr:
            infra[repo]['freshness'] = {k: statistics.median(f[k] for f in fr) for k in fr[0]}
    if any('freshness' in v for v in infra.values()):
        md.append('\nFreshness: graph difference between each bug snapshot and the pinned snapshot (median over category-A tasks) — what a stale index would get wrong without an update:\n')
        md.append('| Repo | edges added | edges removed | nodes added | nodes removed | files with graph changes | stale edge share |')
        md.append('|---|---:|---:|---:|---:|---:|---:|')
        for repo, v in infra.items():
            f = v.get('freshness')
            if f:
                md.append(f"| {repo} | {f['edges_added']:.0f} | {f['edges_removed']:.0f} | {f['nodes_added']:.0f} | {f['nodes_removed']:.0f} | {f['files_with_graph_changes']:.0f} | {f['stale_edge_share']:.5f} |")
    md.append('\nPer-method index preparation and query latency (full corpus; median over tasks; preparation includes loading cached vectors and building the graph engine from the pre-built graph):\n')
    md.append('| Repo | Method | prepare ms | query ms | RSS after (MB, max) | chunks | newly embedded (median) |')
    md.append('|---|---|---:|---:|---:|---:|---:|')
    for repo in ['S', 'M', 'L']:
        ip = f'{EXP}/results/stage1-{repo}/infra.jsonl'
        if not os.path.exists(ip):
            continue
        rows = [json.loads(l) for l in open(ip) if l.strip()]
        rows = [r for r in rows if r['corpus'] == 'full']
        for m in methods:
            mr = [r for r in rows if r['method'] == m]
            if not mr:
                continue
            pm = statistics.median(r['prepare_ms'] for r in mr); qm = statistics.median(r['query_ms'] for r in mr)
            ch = [r['details'].get('chunks') for r in mr if r['details'].get('chunks')]
            ne = [r['details'].get('newly_embedded') for r in mr if r['details'].get('newly_embedded') is not None]
            md.append(f"| {repo} | {m} | {pm:,.0f} | {qm:,.0f} | {max(r['rss_mb_after'] for r in mr):,} | {fmt(ch[0] if ch else None)} | {fmt(statistics.median(ne) if ne else None)} |")
    res['infra'] = infra
    os.makedirs(f'{EXP}/results', exist_ok=True)
    json.dump(res, open(f'{EXP}/results/stage1-analysis-{a.split}.json', 'w'), indent=1, default=str)
    open(f'{EXP}/results/stage1-report-{a.split}.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
